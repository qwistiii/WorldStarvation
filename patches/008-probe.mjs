import fs from 'fs';
const src = fs.readFileSync('src/gen.js', 'utf8');
const out = [];
const fn = (name, len) => { const a = src.indexOf('function ' + name + '('); out.push('######## ' + name + ' @' + a); out.push(a < 0 ? 'NOT FOUND' : src.slice(a, a + len)); };
fn('B', 900); fn('G', 300); fn('drawPrims', 9000); fn('mkRoad', 1500); fn('dropCrowns', 600);
const hits = (re, max, pre, post) => { const r = new RegExp(re, 'g'); let m, n = 0; out.push('######## ' + re); while ((m = r.exec(src)) && n < max) { n++; out.push('--- @' + m.index); out.push(src.slice(Math.max(0, m.index - pre), m.index + post)); } };
hits('\\.rings', 8, 150, 250);
hits('\\.ring\\b', 8, 150, 250);
hits('\\.dgl', 6, 150, 250);
hits('addDiag\\(c\\)', 3, 300, 300);
fs.writeFileSync('docs/probe/slices3.txt', out.join('\n'));
const m = fs.readFileSync('src/main.js', 'utf8');
const a = m.indexOf('function drawClouds');
fs.writeFileSync('docs/probe/main.txt', 'len ' + m.length + ' drawClouds@' + a + '\n' + m.slice(a - 3000, a + 9000));
console.log('ok');
