import fs from 'fs';
const out = [];
const dump = (f, a, b) => { const L = fs.readFileSync(f, 'utf8').split('\n'); out.push('=== ' + f + ' ' + a + '-' + b + ' of ' + L.length); for (let i = a; i <= b && i <= L.length; i++) out.push(i + ': ' + L[i - 1]); };
const grep = (f, re) => { const L = fs.readFileSync(f, 'utf8').split('\n'); out.push('=== grep ' + f + ' ' + re); L.forEach((l, i) => { if (re.test(l)) out.push((i + 1) + ': ' + l.slice(0, 260)); }); };
dump('src/main.js', 40, 125);
dump('src/gen.js', 1495, 1575);
dump('src/gen.js', 2755, 2800);
grep('src/main.js', /dispatch|Worker|requestIdle|budget|queue|pending/);
grep('src/gen.js', /raster\(|Worker|OffscreenCanvas|getImageData/);
fs.mkdirSync('docs/probe', { recursive: true });
fs.writeFileSync('docs/probe/p012.txt', out.join('\n'));
